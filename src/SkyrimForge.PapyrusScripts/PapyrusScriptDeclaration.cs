using Microsoft.CodeAnalysis;
using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text.RegularExpressions;

namespace SkyrimForge.PapyrusScripts;

internal sealed class PapyrusScriptDeclaration
{
    /// <summary>Marks a .psc the generator may delete.</summary>
    internal const string GeneratedCommentPrefix = "; Generated by SkyrimForge from ";

    private const string category = "SkyrimForge.Papyrus";

    // The game enforces this limit at registration.
    private const int maximumParameterCount = 11;

    private static readonly DiagnosticDescriptor unsupportedType = new("SF1001", "Papyrus cannot declare the type",
        "{0} is {1}, which Papyrus cannot declare. Use int, float, bool, string, a form view with a Papyrus script type, such as Actor, "
        + "or a one-dimensional array of one of those.",
        category, DiagnosticSeverity.Error, isEnabledByDefault: true);

    private static readonly DiagnosticDescriptor unsupportedFunction = new("SF1002", "Papyrus cannot declare the function", "{0}",
        category, DiagnosticSeverity.Error, isEnabledByDefault: true);

    private static readonly DiagnosticDescriptor unsupportedScript = new("SF1003", "Papyrus cannot declare the script", "{0}",
        category, DiagnosticSeverity.Error, isEnabledByDefault: true);

    private PapyrusScriptDeclaration(string scriptName, string classFullName, Location attributeLocation, string pscContents, ImmutableArray<Diagnostic> errors)
    {
        ScriptName = scriptName;
        ClassFullName = classFullName;
        AttributeLocation = attributeLocation;
        PscContents = pscContents;
        Errors = errors;
    }

    internal string ScriptName { get; }

    internal string ClassFullName { get; }

    internal Location AttributeLocation { get; }

    internal string PscContents { get; }

    internal ImmutableArray<Diagnostic> Errors { get; }

    /// <summary>Declares each public ordinary method of the class as a native function. PapyrusScriptRegistration registers the same methods.</summary>
    internal static PapyrusScriptDeclaration Read(INamedTypeSymbol scriptClass, AttributeData attribute)
    {
        string scriptName = scriptClass.Name;
        Location attributeLocation = attribute.ApplicationSyntaxReference?.GetSyntax().GetLocation() ?? Location.None;
        List<Diagnostic> errors = [];
        if (!Regex.IsMatch(scriptName, "^[A-Za-z_][A-Za-z0-9_]*$"))
        {
            errors.Add(Diagnostic.Create(unsupportedScript, attributeLocation,
                $"{scriptName} is not a valid Papyrus script name. Use an ASCII letter or an underscore followed by ASCII letters, digits, and underscores."));
        }
        if (scriptClass.IsStatic || scriptClass.IsAbstract || scriptClass.IsGenericType)
        {
            string kind = scriptClass.IsStatic ? "static" : scriptClass.IsAbstract ? "abstract" : "generic";
            errors.Add(Diagnostic.Create(unsupportedScript, attributeLocation,
                $"{scriptName} is {kind}. The framework constructs an instance of the class through its public constructor."));
        }
        if (scriptClass.AllInterfaces.Any(implemented => implemented.ToDisplayString() == "SkyrimForge.IPlugin"))
        {
            errors.Add(Diagnostic.Create(unsupportedScript, attributeLocation,
                $"{scriptName} implements IPlugin. The framework loads it as a plugin and never registers its methods as native functions."));
        }

        ITypeSymbol? extendedType = attribute.NamedArguments.FirstOrDefault(argument => argument.Key == "Extends").Value.Value as ITypeSymbol;
        string? extendedScriptName = null;
        if (extendedType != null && !PapyrusTypeNames.Known.TryGetValue(extendedType.ToDisplayString(), out extendedScriptName))
        {
            errors.Add(Diagnostic.Create(unsupportedScript, attributeLocation,
                $"{extendedType.ToDisplayString()} has no Papyrus script type, so {scriptName} cannot extend it."));
        }

        ImmutableArray<ISymbol> members = scriptClass.GetMembers();
        foreach (IPropertySymbol property in members.OfType<IPropertySymbol>().Where(property => property.DeclaredAccessibility == Accessibility.Public))
        {
            string replacement = property.SetMethod?.DeclaredAccessibility == Accessibility.Public ? $"Get{property.Name} and Set{property.Name} methods" : $"a Get{property.Name} method";
            errors.Add(Diagnostic.Create(unsupportedFunction, GetLocation(property),
                $"{property.Name} is a property, and Papyrus has no native properties. Declare {replacement} instead."));
        }

        IMethodSymbol[] methods = [.. members.OfType<IMethodSymbol>().Where(method => method.MethodKind == MethodKind.Ordinary && method.DeclaredAccessibility == Accessibility.Public)];
        foreach (IGrouping<string, IMethodSymbol> sharedNameGroup in methods.GroupBy(method => method.Name, StringComparer.OrdinalIgnoreCase).Where(group => group.Count() > 1))
        {
            string spellings = string.Join(" and ", sharedNameGroup.Select(method => method.Name).Distinct());
            errors.AddRange(sharedNameGroup.Select(method => Diagnostic.Create(unsupportedFunction, GetLocation(method),
                $"The methods named {spellings} declare one Papyrus function. Papyrus has no overloads and ignores case in names.")));
        }
        List<string> functionDeclarations = [];
        foreach (IMethodSymbol method in methods)
        {
            if (GetFunctionDeclaration(method, scriptName, extendedType, errors) is { } functionDeclaration)
            {
                functionDeclarations.Add(functionDeclaration);
            }
        }

        // Hidden removes a script that cannot be attached to a form from the Creation Kit's lists.
        string header = extendedScriptName != null ? $"Scriptname {scriptName} extends {extendedScriptName}" : $"Scriptname {scriptName} Hidden";
        string classFullName = scriptClass.ToDisplayString();
        string pscContents = $"{header}\r\n\r\n{GeneratedCommentPrefix}{classFullName}. Do not edit.\r\n\r\n" + string.Join("\r\n", functionDeclarations);
        return new PapyrusScriptDeclaration(scriptName, classFullName, attributeLocation, pscContents, [.. errors]);
    }

    internal static IEnumerable<Diagnostic> CreateSharedNameErrors(IEnumerable<PapyrusScriptDeclaration> scripts) =>
        scripts.Select(script => Diagnostic.Create(unsupportedScript, script.AttributeLocation,
            $"{string.Join(" and ", scripts.Select(other => other.ClassFullName))} declare the same Papyrus script. A script has its class's name, and Papyrus ignores case in script names."));

    private static string? GetFunctionDeclaration(IMethodSymbol method, string scriptName, ITypeSymbol? extendedType, List<Diagnostic> errors)
    {
        Location methodLocation = GetLocation(method);
        List<Diagnostic> methodErrors = [];
        if (method.IsGenericMethod)
        {
            methodErrors.Add(Diagnostic.Create(unsupportedFunction, methodLocation, $"{method.Name} is generic. A Papyrus function cannot be generic."));
        }

        // Papyrus passes the attached form as Self, so the .psc declares no parameter for it.
        bool receivesSelf = method.Parameters.Length > 0 && IsMarkedSelf(method.Parameters[0]);
        if (receivesSelf && extendedType == null)
        {
            methodErrors.Add(Diagnostic.Create(unsupportedFunction, methodLocation,
                $"{method.Name} has a [PapyrusSelf] parameter, and {scriptName} extends no form type. Set Extends on its PapyrusScript attribute."));
        }
        else if (receivesSelf && !SymbolEqualityComparer.Default.Equals(method.Parameters[0].Type, extendedType))
        {
            methodErrors.Add(Diagnostic.Create(unsupportedFunction, methodLocation,
                $"Parameter {method.Parameters[0].Name} of {method.Name} is {method.Parameters[0].Type.ToDisplayString()}. A [PapyrusSelf] parameter must be the type {scriptName} extends."));
        }
        ImmutableArray<IParameterSymbol> papyrusParameters = receivesSelf ? method.Parameters.RemoveAt(0) : method.Parameters;
        if (papyrusParameters.Length > maximumParameterCount)
        {
            methodErrors.Add(Diagnostic.Create(unsupportedFunction, methodLocation,
                $"{method.Name} declares {papyrusParameters.Length} parameters, and a Papyrus native function declares at most {maximumParameterCount}."));
        }

        if (method.RefKind != RefKind.None)
        {
            methodErrors.Add(Diagnostic.Create(unsupportedFunction, methodLocation, $"{method.Name} returns by reference, and Papyrus receives every return value by value."));
        }
        string? returnTypePrefix = method.ReturnsVoid ? "" : GetPapyrusType(method.ReturnType) is { } returnType ? returnType + " " : null;
        if (returnTypePrefix == null)
        {
            methodErrors.Add(Diagnostic.Create(unsupportedType, methodLocation, $"The return value of {method.Name}", method.ReturnType.ToDisplayString()));
        }
        List<string> parameterDeclarations = [];
        foreach (IParameterSymbol parameter in papyrusParameters)
        {
            if (IsMarkedSelf(parameter))
            {
                methodErrors.Add(Diagnostic.Create(unsupportedFunction, GetLocation(parameter),
                    $"Parameter {parameter.Name} of {method.Name} is marked [PapyrusSelf]. Only a method's first parameter can be."));
            }
            if (parameter.RefKind != RefKind.None)
            {
                methodErrors.Add(Diagnostic.Create(unsupportedFunction, GetLocation(parameter),
                    $"Parameter {parameter.Name} of {method.Name} is passed by reference, and Papyrus passes every argument by value."));
            }
            if (GetPapyrusType(parameter.Type) is { } parameterType)
            {
                parameterDeclarations.Add($"{parameterType} {parameter.Name}");
            }
            else
            {
                methodErrors.Add(Diagnostic.Create(unsupportedType, GetLocation(parameter), $"Parameter {parameter.Name} of {method.Name}", parameter.Type.ToDisplayString()));
            }
        }

        errors.AddRange(methodErrors);
        if (returnTypePrefix == null || methodErrors.Count > 0)
        {
            return null;
        }
        string comment = DocumentationSummary.Read(method) is { } summary ? $"; {summary}\r\n" : "";
        return $"{comment}{returnTypePrefix}Function {method.Name}({string.Join(", ", parameterDeclarations)}) {(receivesSelf ? "native" : "global native")}\r\n";
    }

    private static bool IsMarkedSelf(IParameterSymbol parameter) =>
        parameter.GetAttributes().Any(attribute => attribute.AttributeClass?.ToDisplayString() == "SkyrimForge.Papyrus.PapyrusSelfAttribute");

    private static Location GetLocation(ISymbol symbol) => symbol.Locations.FirstOrDefault() ?? Location.None;

    private static string? GetPapyrusType(ITypeSymbol type) =>
        type is IArrayTypeSymbol { Rank: 1 } array ? GetNonArrayType(array.ElementType) is { } elementType ? elementType + "[]" : null : GetNonArrayType(type);

    private static string? GetNonArrayType(ITypeSymbol type)
    {
        ITypeSymbol underlyingType = type is INamedTypeSymbol { OriginalDefinition.SpecialType: SpecialType.System_Nullable_T } nullable ? nullable.TypeArguments[0] : type;
        return underlyingType.SpecialType switch
        {
            SpecialType.System_Int32 => "int",
            SpecialType.System_Single => "float",
            SpecialType.System_Boolean => "bool",
            SpecialType.System_String => "string",
            _ => PapyrusTypeNames.Known.TryGetValue(underlyingType.ToDisplayString(), out string? papyrusType) ? papyrusType : null
        };
    }
}
